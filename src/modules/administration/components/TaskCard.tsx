"use client";

import { Badge } from "@/components/ui/badge";
import { MessageSquare, CalendarClock, Repeat } from "lucide-react";
import UserAvatar from "@/shared/components/UserAvatar";
import { PRIORITY_META } from "@/utils/constants";
import { formatDate } from "@/shared/lib/format";
import { useNow } from "@/shared/hooks";
import type { TaskDto, TaskPriority } from "../lib/types";

/** Left-edge accent per priority — quick visual scan down a column. */
const PRIORITY_ACCENT: Record<TaskPriority, string> = {
    LOW: "border-l-gray-300",
    MEDIUM: "border-l-blue-400",
    HIGH: "border-l-orange-400",
    URGENT: "border-l-red-500",
};

export default function TaskCard({
    task,
    draggable,
    onDragStart,
    onClick,
}: {
    task: TaskDto;
    draggable: boolean;
    onDragStart?: (e: React.DragEvent) => void;
    onClick: () => void;
}) {
    const priority = PRIORITY_META[task.priority] ?? PRIORITY_META.MEDIUM;
    const accent = PRIORITY_ACCENT[task.priority] ?? PRIORITY_ACCENT.MEDIUM;
    // "now" read in an effect (useNow) — calling Date.now() during render trips react-hooks/purity.
    const now = useNow();
    const overdue =
        task.dueDate && !task.completedAt && new Date(task.dueDate).getTime() < now;

    // Effective owner = whoever currently holds the assigned seat.
    const holders = task.assignedPosition?.holders.map((h) => h.user) ?? [];
    const holder = holders[0] ?? null;
    const holderLabel =
        holders.length === 0
            ? "Vacant"
            : holders.length === 1
                ? holder!.name
                : `${holder!.name} +${holders.length - 1}`;

    return (
        <button
            type="button"
            draggable={draggable}
            onDragStart={onDragStart}
            onClick={onClick}
            className={`w-full cursor-pointer rounded-lg border border-l-4 bg-card p-3 text-left shadow-sm transition hover:-translate-y-0.5 hover:shadow-md focus:outline-none focus:ring-2 focus:ring-ring ${accent} ${
                draggable ? "active:cursor-grabbing" : ""
            }`}
        >
            <div className="flex items-start justify-between gap-2">
                <span className="text-sm font-medium leading-snug">{task.title}</span>
                <Badge className={`shrink-0 ${priority.color}`}>{priority.label}</Badge>
            </div>

            <div className="mt-2 flex flex-wrap items-center gap-1">
                {task.category && (
                    <span className="inline-block rounded bg-muted px-1.5 py-0.5 text-[11px] text-muted-foreground">
                        {task.category}
                    </span>
                )}
                {/* Generated by a recurring task. The "#3 of 12" context is already
                    in the title, so this stays a small "this one repeats" signal. */}
                {task.recurrenceId != null && (
                    <span className="inline-flex items-center gap-1 rounded bg-primary/10 px-1.5 py-0.5 text-[11px] text-primary">
                        <Repeat className="size-3" />#{task.occurrenceNo}
                    </span>
                )}
            </div>

            <div className="mt-3 flex items-center justify-between gap-2 text-xs text-muted-foreground">
                <div className="flex min-w-0 items-center gap-2">
                    {task.assignedPosition ? (
                        <span className="flex min-w-0 items-center gap-1.5">
                            {holder && (
                                <UserAvatar
                                    name={holder.name}
                                    avatarUrl={holder.avatarUrl}
                                    role={holder.role}
                                    sizePx={20}
                                />
                            )}
                            <span className="flex min-w-0 flex-col leading-tight">
                                <span className="max-w-[120px] truncate font-medium text-foreground/80">
                                    {task.assignedPosition.title}
                                </span>
                                <span className={`max-w-[120px] truncate text-[10px] ${holders.length === 0 ? "italic" : ""}`}>
                                    {holderLabel}
                                </span>
                            </span>
                        </span>
                    ) : (
                        <span className="italic">Unassigned</span>
                    )}
                </div>
                <div className="flex items-center gap-3">
                    {task._count.comments > 0 && (
                        <span className="flex items-center gap-1">
                            <MessageSquare className="size-3" />
                            {task._count.comments}
                        </span>
                    )}
                    {task.dueDate && (
                        <span className={`flex items-center gap-1 ${overdue ? "text-red-600" : ""}`}>
                            <CalendarClock className="size-3" />
                            {formatDate(task.dueDate)}
                        </span>
                    )}
                </div>
            </div>
        </button>
    );
}
